"""Write the M1 input files that are exported from measurements (deterministic).

  lib/workload/mini_coder_4b_trace.tsv   one row per turn of the 89-session workload
                                         (common.sessions(): states, tau, GPU times)
  lib/host/i9_12900k.yaml                the host profile: per-kind measured CPU curves
                                         (results/cpu/cpu_ops.tsv, 8 threads) and the
                                         roofline fallback of lib/tech/host.yaml `cpu`

Usage: python experiments/export_inputs.py   (rerun only if the traces or profile change)
"""

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "experiments"))

from common import sessions  # noqa: E402
from harness.tech import CpuProfile, load_library  # noqa: E402
from harness.workload import load_workload, write_trace_tsv  # noqa: E402

TRACE = ROOT / "lib/workload/mini_coder_4b_trace.tsv"
HOST = ROOT / "lib/host/i9_12900k.yaml"


def host_yaml():
    cpu = load_library(ROOT / "lib/tech/host.yaml")["cpu"]
    prof = CpuProfile(ROOT / cpu.p("profile_tsv"), cpu.p("threads"))
    ops = load_workload(ROOT / "lib/workload/mini_coder_4b.yaml").forward_ops(1, 1024)
    cls_of = {}
    for op in ops:
        cls_of.setdefault(op.kind, op.cls)
    by_cls = {}
    for kind, c in cls_of.items():
        by_cls.setdefault(c, {"measured": [], "roofline": []})[
            "measured" if prof.has(kind) else "roofline"].append(kind)
    L = [
        "# Host profile: the cost of every op left on the host CPU, as one input.",
        "# Generated by experiments/export_inputs.py from results/cpu/cpu_ops.tsv (rows for",
        f"# {int(cpu.p('threads'))} threads, measured by profile/cpu_ops.c) and the `cpu` entry of",
        "# lib/tech/host.yaml (roofline fallback). Loaded by harness.inputs.HostProfile.from_file.",
        "#",
        "# Cost of an op of kind k on the host at context L, for a step of n tokens:",
        "#   measured kind:  n * interp(L; measured[k])   (linear extrapolation past the last point)",
        "#   other kinds:    max(flops / ops_per_s, bytes / mem_bw_Bps) + op_overhead_s",
        "# Per op class, at the workload's sizes (mini-coder-4b):",
    ]
    for c in sorted(by_cls):
        L.append(f"#   {c:12s} measured: {', '.join(by_cls[c]['measured']) or '-'};"
                 f" roofline: {', '.join(by_cls[c]['roofline']) or '-'}")
    L += [
        "# Tool times tau are not here: they are measured on this same host and stored per turn in",
        "# the workload trace (lib/workload/mini_coder_4b_trace.tsv, column t_tool_s); tool_scale",
        "# rescales them for a different host (1.0 = the traced host).",
        "",
        f"name: {cpu.name}",
        'host: "Intel i9-12900K, 8 threads"',
        f'source: "{cpu.source}"',
        f"maturity: {cpu.maturity}",
        f"supports: [{', '.join(cpu.supports)}]",
        f"threads: {int(cpu.p('threads'))}",
        "tool_scale: 1.0",
        "roofline:",
        f"  ops_per_s: {cpu.p('ops_per_s')!r}",
        f"  mem_bw_Bps: {cpu.p('mem_bw_Bps')!r}",
        f"  op_overhead_s: {cpu.p('op_overhead_s')!r}",
        "sources:",
    ]
    for k, v in cpu.sources.items():
        L.append(f'  {k}: "{v}"')
    L.append('  measured: "profile/cpu_ops.c on this host (results/cpu/cpu_ops.tsv, H3)"')
    L.append("measured:    # kind: [[ctx, seconds per token], ...]; triad_64M gives STREAM bandwidth")
    for kind in sorted(prof.by_kind):
        pts = ", ".join(f"[{c}, {s!r}]" for c, s in prof.by_kind[kind])
        L.append(f"  {kind}: [{pts}]")
    return "\n".join(L) + "\n"


def main():
    write_trace_tsv(sessions(), TRACE)
    HOST.parent.mkdir(parents=True, exist_ok=True)
    HOST.write_text(host_yaml())
    print(f"wrote {TRACE.relative_to(ROOT)} and {HOST.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
